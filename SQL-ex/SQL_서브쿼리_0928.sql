-- ======================================================================================
-- 사용 위치에 따른 서브 쿼리
--  [예제 6-8] 고객 전체의 평균마일리지보다 평균마일리지가 큰 도시에 대해 
-- 도시명과 도시의 평균마일리지를 보이시오.
select avg(마일리지) from 고객;
select 도시, avg(마일리지) 평균마일리지
from 고객
group by 도시
having avg(마일리지) > (select avg(마일리지) from 고객);

-- FROM절의 서브쿼리 인라인뷰=================================================================

-- [예제 6-9] 담당자명, 고객회사명, 마일리지, 도시, 해당 도시의 
-- 평균마일리지를 보이시오. 그리고 고객이 위치하는 도시의 평균마일리지와 
-- 각 고객의 마일리지 간의 차이도 함께 보이시오
select 도시, avg(마일리지) 평균마일리지
from 고객
group by 도시;

select 고객.담당자명, 고객.고객회사명, 고객.마일리지, 고객.도시, 도시평균마일리지.평균마일리지, (도시평균마일리지.평균마일리지 - 고객.마일리지) 마일리지_차이
from 고객,
	(select 도시, avg(마일리지) 평균마일리지
		from 고객
		group by 도시) as 도시평균마일리지
where 고객.도시 = 도시평균마일리지.도시;
-- 문제를 읽고 생각해야할 논리적 절차.
-- 1.고객테이블과 도시별요약 테이블이 있따고 생각한다.
-- 2.두 테이블의 공통컬럼 '도시'를 기반으로 조인 조건 작성(inner join 처럼 생각한다.)
-- 3.도시 컬럼이 양쪽에 다 존재하기에 도시를 볼때는 고객.도시 or 도시평균마일리지.도시로 볼 수 있음
-- 4.도시를 공통 컬럼으로 조인하면 각 고객에 대하여 고객이 위치한 도시의 평균마일리지를 행단위로 얻을 수 있다.
-- 5. 고객이 위치한 도시의 편균마일리지와 각 고객의 마일리지의 차이도 구할 수 있다.


