# 외부 조인 방법
select 제품.*, (제품.재고*제품.단가) 재고금액
from 제품
left outer join 주문세부
on 제품.제품번호 = 주문세부.제품번호
where 주문세부.제품번호 is null;

# 상관 서브 쿼리 방법
select *, p.재고*p.단가 as 재고금액
from 제품 p
where Not exists(select* from 주문세부 d where d.제품번호 = p.제품번호);

