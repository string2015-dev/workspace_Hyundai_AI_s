#### 3. 회원 등급 필터링 시스템 — `[제어문 + 반복문 + 함수]`
# - **시나리오**: 회원 목록에서 나이/구매금액 조건에 맞는 회원만 뽑아 등급을 부여합니다.
# - **요구사항**:
#     1. 구매금액이 100만원 이상이면 "VIP", 50만원 이상이면 "일반", 그 미만이면 "신규"로 등급을 매기는 함수 `get_grade(amount)`
#     2. 회원 리스트를 순회하며 각 회원의 등급을 딕셔너리에 추가
#     3. "VIP" 등급 회원만 따로 리스트로 출력
# - 🎯 **포인트**:  실무의 "고객 세그멘테이션(고객 분류)" 로직 미니 버전입니다. 마케팅/CRM 도메인 프로젝트로 확장할 수 있습니다.
#======================================================================
members = [
     {"이름": "김부자","구매금액":500000000, "나이":10, "등급":"신규"},
     {"이름": "이서민", "구매금액":600000, "등급":"신규"},
     {"이름": "박중산", "구매금액":20000,"등급":"신규"},
     {"이름": "최간아", "구매금액":12000000,"등급":"신규"}
]
#1. 등급 매기는 함수.
def get_grade(amount):
        if amount >=1000000:
            return "vip"
        elif amount >=500000:
            return "일반"
        else: return "신규"

#2. 구매금액에 따라 등급 갱신하는 함수
def change_grade():
     for member in members:
          member["등급"] = get_grade(member["구매금액"])

#3. vip 등급 따로 뽑는 함수
def vip_custom():
    vip_list = [member["이름"] for member in members if member["등급"] == "vip"]
    return vip_list
change_grade()
print(vip_custom())