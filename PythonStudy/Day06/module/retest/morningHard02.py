#### 2. 온라인 쇼핑몰 장바구니 계산기 — `[리스트/딕셔너리 + 함수 + 제어문]`
# - **시나리오**: 장바구니에 담긴 상품(이름, 가격, 수량)의 총 결제금액을 계산합니다.
#   cart = [      {"상품명": "키보드", "가격": 50000, "수량": 1},      {"상품명": "마우스", "가격": 20000, "수량": 2},  ]
# - **요구사항**:
#     1. 총 금액을 계산하는 함수 `calculate_total(cart)`
#     2. 총 금액이 **50,000원 이상이면 10% 할인**을 적용하는 조건문 추가
#     3. 최종 결제 금액 출력
# - 💡 **비유**: 실제 쇼핑몰 백엔드의 "장바구니 로직"이 바로 이런 구조예요. 지금 짜는 이 함수가 나중에 실제 서비스의 핵심 로직이 될 수 있습니다.
#======================================================================
cart = [      {"상품명": "키보드", "가격": 50000, "수량": 1},      
        {"상품명": "마우스", "가격": 20000, "수량": 2},  ]
#1. 총 금액을 계산 하는 함수
def calculate_total(cart):
    total = sum([item["가격"]*item["수량"] for item in cart])
    return total
#2. 금액이 50,000원 이상이면 10%할인 하는 함수.
def total_discount():
    if calculate_total(cart) >= 50000:
        discount = calculate_total(cart)*0.9
        return discount
    else:
        return calculate_total(cart)
#3. 최종 결제 금액 출력
print(f"총금액: {calculate_total(cart):,}원 결제금액: {total_discount():,.0f}원")