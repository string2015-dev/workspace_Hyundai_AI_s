#======================================================================
#### 1. 리스트로 평균 구하기 — `[데이터구조 + 반복문]`
# - **문제**: 학생 5명의 점수가 담긴 리스트 `scores = [85, 92, 78, 90, 88]`이 있습니다. `for`문을 사용해 총합과 평균을 구해 출력하세요.
# - 💡 **비유**: 리스트는 "물건을 순서대로 넣어두는 서랍장"과 같아요. 서랍을 하나씩(`for`) 열어보면서 안에 든 숫자를 꺼내 더하는 작업.
# - **출력 예시**: `총합: 433, 평균: 86.6`
#======================================================================
scores = [85, 92, 78, 90, 88]
# for 문을 이용한 총합, 빈 값을 만들어 둔다.
sum = 0
for i in scores:
    sum += i #sum에 i값을 누적시켜 더한다.
# for문을 돌고 나면 sum에 scores의 총합이 들어있다.
average = sum/len(scores)
print(f"총합: {sum}, 평균: {average:.1f}")