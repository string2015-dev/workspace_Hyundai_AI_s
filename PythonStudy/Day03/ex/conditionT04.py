# #1. 입력받은 점수를 “ABCDF”로 평가하는 프로그램을 작성하시오. 

#       (조건: 90점 이상 A , 80점 이상 B, 70점 이상 C, 

#                 60점 이상 D,60점 미만 F)

#1. 점수를 입력받을 수 있어야함
sco = int(input("점수를 입력하세요: "))
# inpu() 하나가 필요함.
#조건분기를 5가지로 설정해 평가하는 프로그램작성
if sco>= 90:
    print("A")
elif 90 > sco >= 80 :
    print("B")
elif 80 > sco >= 70 :
    print("C")
else:
    print("D")